    /// <summary>The seven continents, in name order.</summary>
    public static IReadOnlyList<Continent> All { get; } = [.. Enum.GetValues<Continent>()];

    /// <summary>The continent of a country, or null when the country isn't in the table.</summary>
    public static Continent? Of(Country country)
    {
        ArgumentNullException.ThrowIfNull(country);
        return Table.TryGetValue(country.Key, out var continent) ? continent : null;
    }

    /// <summary>The display name, such as "North America".</summary>
    public static string Name(Continent continent) => continent switch
    {
        Continent.NorthAmerica => "North America",
        Continent.SouthAmerica => "South America",
        _ => continent.ToString(),
    };

    /// <summary>The route slug, such as "north-america".</summary>
    public static string Slug(Continent continent) => Name(continent).ToLowerInvariant().Replace(' ', '-');

    /// <summary>Reads a route slug, or returns null.</summary>
    public static Continent? FromSlug(string slug) => All.Cast<Continent?>().FirstOrDefault(c => Slug(c!.Value) == slug);

    /// <summary>The number of outlines on each continent. Outlines that share a code count once.</summary>
    public static IReadOnlyDictionary<Continent, int> Totals(IEnumerable<CountryOutline> outlines)
    {
        ArgumentNullException.ThrowIfNull(outlines);
        var totals = All.ToDictionary(c => c, _ => 0);
        foreach (var country in outlines.Select(o => new Country(o.Id, o.Name)).DistinctBy(c => c.Key))
        {
            if (Of(country) is { } continent) totals[continent]++;
        }
        return totals;
    }
